"""Deterministically export Pydantic schemas and derived TypeScript. No routes."""

import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter
from pydantic.json_schema import models_json_schema

from . import models
from .fixtures import synthetic_inventory_a


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return "(" + " | ".join(typescript(x) for x in schema[union]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "ReadonlyArray<" + typescript(schema["items"]) + ">"
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  readonly {json.dumps(k)}{'' if k in required else '?'}: {typescript(v)};"
                for k, v in schema.get("properties", {}).items()
            )
            + "\n}"
        )
    primitives = {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind not in primitives:
        raise ValueError(f"Unsupported JSON Schema for TypeScript generation: {schema}")
    return primitives[kind]


def artifacts():
    records = sorted(
        (
            v
            for v in vars(models).values()
            if isinstance(v, type)
            and issubclass(v, models.Record)
            and v is not models.Record
        ),
        key=lambda cls: cls.__name__,
    )
    _, bundle = models_json_schema([(cls, "validation") for cls in records])
    definitions = bundle["$defs"]
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "FORMA contracts",
        "$defs": definitions,
    }
    _, api = models_json_schema(
        [(cls, "validation") for cls in records],
        ref_template="#/components/schemas/{model}",
    )
    openapi = {
        "openapi": "3.1.0",
        "info": {"title": "FORMA contract components", "version": "0.1.0"},
        "paths": {},
        "components": {"schemas": api["$defs"]},
    }
    ts = "// Generated by python -m forma_domain.generate. Do not edit.\n\n"
    ts += "\n\n".join(
        f"export type {name} = {typescript(value)};"
        for name, value in sorted(definitions.items())
    )
    operation = TypeAdapter(models.Operation).json_schema()
    ts += "\n\nexport type Operation = " + typescript(operation) + ";\n"
    fixture = {
        "label": "SYNTHETIC inventory A: software fixture only; not measured or physically tested",
        "stocks": [s.model_dump(mode="json") for s in synthetic_inventory_a()],
    }

    def encode(value):
        return json.dumps(value, indent=2, sort_keys=True) + "\n"

    return {
        "packages/domain/generated/contracts.schema.json": encode(schema),
        "packages/domain/generated/openapi.json": encode(openapi),
        "packages/domain/generated/synthetic-inventory-a.json": encode(fixture),
        "apps/web/src/lib/generated/contracts.ts": ts,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[4]
    stale = []
    for relative, content in artifacts().items():
        path = root / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale generated contracts: " + ", ".join(stale))
    print(
        "Generated contracts are current"
        if args.check
        else "Generated four contract artifacts"
    )


if __name__ == "__main__":
    main()
