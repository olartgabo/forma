"""Generate browser API types from route-owned Pydantic records."""

import argparse
from pathlib import Path

from pydantic.json_schema import models_json_schema

from forma_api.media import Media, MediaDeleteResult, MediaList, MediaResult
from forma_api.projects import (
    BuildRequirements,
    CreateProject,
    DeleteResult,
    InventoryUpdate,
    Project,
    ProjectResult,
)
from forma_domain import models
from forma_domain.generate import typescript

API_RECORDS = (
    BuildRequirements,
    CreateProject,
    DeleteResult,
    InventoryUpdate,
    Media,
    MediaDeleteResult,
    MediaList,
    MediaResult,
    Project,
    ProjectResult,
)
OUTPUT = "apps/web/src/lib/generated/api-contracts.ts"


def artifacts():
    _, bundle = models_json_schema([(record, "validation") for record in API_RECORDS])
    names = {record.__name__ for record in API_RECORDS}
    definitions = bundle["$defs"]

    def references(schema):
        if isinstance(schema, dict):
            if "$ref" in schema:
                yield schema["$ref"].rsplit("/", 1)[-1]
            for value in schema.values():
                yield from references(value)
        elif isinstance(schema, list):
            for value in schema:
                yield from references(value)

    shared = sorted(
        {ref for name in names for ref in references(definitions[name])} - names
    )
    for name in shared:
        if not isinstance(getattr(models, name, None), type) or not issubclass(
            getattr(models, name), models.Record
        ):
            raise ValueError(f"API schema references an unknown domain record: {name}")
    content = "// Generated by python -m forma_api.generate. Do not edit.\n\n"
    if shared:
        content += "import type { " + ", ".join(shared) + ' } from "./contracts";\n\n'
    content += "\n\n".join(
        f"export type {name} = {typescript(definitions[name])};"
        for name in sorted(names)
    )
    return {OUTPUT: content + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[4]
    stale = []
    for relative, content in artifacts().items():
        path = root / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale generated API contracts: " + ", ".join(stale))
    print(
        "Generated API contracts are current" if args.check else "Generated API types"
    )


if __name__ == "__main__":
    main()
